import SwiftUI

/// Language selection, persisted in UserDefaults ("system" follows macOS).
final class LanguageManager: ObservableObject {
    nonisolated(unsafe) static let shared = LanguageManager()

    @Published var languageCode: String

    init() {
        languageCode = UserDefaults.standard.string(forKey: "appLanguage") ?? "system"
    }

    var resolved: String {
        if languageCode == "system" {
            return Locale.preferredLanguages.first?.lowercased().hasPrefix("en") == true ? "en" : "zh-Hans"
        }
        return languageCode
    }

    func setLanguage(_ code: String) {
        languageCode = code
        UserDefaults.standard.set(code, forKey: "appLanguage")
    }
}

